export const inject = ['locale']

/** Registra pt-BR e o torna o idioma padrão do produto Toranja. */
export function apply(ctx: ClientContext): void {
  const disposers: Array<() => void> = []
  disposers.push(ctx.locale.addLanguage({ id: 'pt-BR', label: 'Português (Brasil)', fallback: 'en' }))
  for (const [namespace, dictionary] of Object.entries(dictionaries)) {
    disposers.push(ctx.locale.register(namespace, 'pt-BR', dictionary))
  }
  ctx.locale.setLocale('pt-BR')
  ctx.effect(() => () => { for (const dispose of disposers.reverse()) dispose() }, 'toranja: idioma pt-BR')
}
